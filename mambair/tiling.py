"""Bounded, feathered inference.

The selective scan is *global per tile*, so the tile edge is a quality dial as well
as a speed and memory one: the peak per tile is the network's own activation maps,
which grow with the tile. This module therefore bounds every forward pass at a cap
that depends on the device, never on the input size.

Blending follows ComfyUI's own convention (linear ramp over the overlap, output
divided by the accumulated mask), so a constant-colour image stays constant.
"""

from __future__ import annotations

import gc
import logging

import torch

log = logging.getLogger("MambaIR")

__all__ = ["default_tile_cap", "tile_count", "tiled_forward", "bounded_forward"]

MIN_CAP = 128


def default_tile_cap(device=None) -> int:
    """Default internal cap: 320 px on a GPU, 256 px on the CPU.

    Larger tiles are both faster and better for the global scan (more context) until the working
    set stops fitting; throughput is flat-to-better through 320 px and collapses beyond it. The
    reason not to go small is fixed overhead plus overlap: every tiled pass re-reads a margin, so
    the work per useful pixel is ``(tiles * tile**2) / (H * W)`` -- 2.56x for a 320 px image at a
    256 px cap, where a 320 px cap is a single tile -- while the asymptotic
    ``(tile / (tile - overlap))**2`` is 1.31x at 256/32.

    Caps above 320 px are left to the node's widget. Numbers live in the README benchmark table,
    regenerated by ``python tests/bench.py --write``.
    """
    if device is not None:
        kind = getattr(device, "type", str(device))
        return 320 if kind in ("cuda", "xpu") else 256
    return 320 if torch.cuda.is_available() else 256


def _positions(size: int, tile: int, overlap: int) -> list[int]:
    """Tile origins covering ``size``, last tile flush with the edge."""
    if size <= tile:
        return [0]
    step = max(1, tile - overlap)
    out = [0]
    while out[-1] + tile < size:
        out.append(min(out[-1] + step, size - tile))
    return out


def tile_count(h: int, w: int, tile: int, overlap: int) -> int:
    """How many tiles :func:`tiled_forward` will run, using the same grid it uses.

    Exists so the progress total is derived from the same grid the runner walks, instead of
    from a duplicated guess at the cap.
    """
    tile = max(1, int(tile))
    overlap = max(0, min(int(overlap), max(0, tile // 2)))
    return len(_positions(h, tile, overlap)) * len(_positions(w, tile, overlap))


def _tick(progress, n: int = 1) -> None:
    """Drive ComfyUI's ProgressBar (``.update``) or any plain callable."""
    if progress is None:
        return
    update = getattr(progress, "update", None)
    if callable(update):
        update(n)
    elif callable(progress):
        progress(n)


def _ramp(n: int, rising: bool) -> torch.Tensor:
    """A linear ramp of ``n`` values in ``(0, 1)``, rising or falling."""
    values = torch.arange(1, n + 1, dtype=torch.float32) / (n + 1)
    return values if rising else values.flip(0)


def _mask_2d(lh: int, lw: int, y: int, x: int, h: int, w: int, overlap: int) -> torch.Tensor:
    """Blend weights for one tile: ramps on the edges that do not touch the image border."""
    my = torch.ones(lh)
    mx = torch.ones(lw)
    ky = min(overlap, lh // 2)
    kx = min(overlap, lw // 2)
    if y > 0 and ky > 0:
        my[:ky] = _ramp(ky, rising=True)
    if y + lh < h and ky > 0:
        my[lh - ky:] = _ramp(ky, rising=False)
    if x > 0 and kx > 0:
        mx[:kx] = _ramp(kx, rising=True)
    if x + lw < w and kx > 0:
        mx[lw - kx:] = _ramp(kx, rising=False)
    return (my[:, None] * mx[None, :]).clamp_min(1e-6)


def _check_scale(scale: int, produced: int) -> int:
    """Return the scale the model really produced, warning when it disagrees with the label.

    Trusting the tensor over the advertised value is what turns a mislabelled descriptor from a
    shape-mismatch crash into a diagnosis (see
    tests/test_hardening.py::test_bug_5_scale_mismatch_recovers).
    """
    if produced != scale:
        log.warning(
            "MambaIR: model reports x%d but produced x%d; using x%d", scale, produced, produced
        )
    return produced


def tiled_forward(fn, x: torch.Tensor, scale: int, tile: int, overlap: int, progress=None):
    """Run ``fn`` over ``x`` in overlapping tiles and blend the result.

    Blending is a linear ramp over the overlap with the output divided by the accumulated mask, so
    a constant-colour image stays constant. ``fn`` is never given a tile larger than ``tile`` on
    either edge.

    Args:
        fn: Callable mapping ``(n, c, h, w)`` to ``(n, c, h*s, w*s)``.
        x: Input, ``(n, c, h, w)``.
        scale: Advertised output scale; the first tile's real ratio overrides it, with a warning.
        tile: Maximum tile edge in pixels.
        overlap: Feathered overlap in pixels, clamped to ``tile // 2``.
        progress: Optional ComfyUI ``ProgressBar`` or any callable, ticked once per tile.

    Returns:
        The blended output, ``(n, c, h*s, w*s)``.

    Note:
        The result differs from one untiled pass: the scan is global per tile, so seams are blended
        rather than continuous (see README).
    """
    n, _, h, w = x.shape
    tile = max(1, int(tile))
    if overlap >= tile:  # the mask ramp already assumes <= tile // 2
        clamped = max(1, tile // 2)
        log.debug("MambaIR: overlap %d >= tile %d; clamping to %d", overlap, tile, clamped)
        overlap = clamped
    if h <= tile and w <= tile:
        out = fn(x)
        _check_scale(scale, out.shape[-1] // max(1, w))
        _tick(progress, n)
        return out

    ys = _positions(h, tile, overlap)
    xs = _positions(w, tile, overlap)

    out = None
    acc = None
    for y in ys:
        for x0 in xs:
            y1 = min(y + tile, h)
            x1 = min(x0 + tile, w)
            sub = x[:, :, y:y1, x0:x1]
            got = fn(sub)
            if out is None:
                scale = _check_scale(scale, got.shape[-1] // max(1, x1 - x0))
                out = torch.zeros(
                    (got.shape[0], got.shape[1], h * scale, w * scale),
                    dtype=got.dtype,
                    device=got.device,
                )
                acc = torch.zeros((1, 1, h * scale, w * scale), dtype=got.dtype, device=got.device)
            mask = _mask_2d(y1 - y, x1 - x0, y, x0, h, w, overlap).to(got.dtype)
            mask = mask.to(got.device)
            if scale != 1:
                mask = torch.nn.functional.interpolate(
                    mask[None, None], size=got.shape[-2:], mode="nearest"
                )[0, 0]
            out[:, :, y * scale:y1 * scale, x0 * scale:x1 * scale] += got * mask
            acc[:, :, y * scale:y1 * scale, x0 * scale:x1 * scale] += mask
            _tick(progress, sub.shape[0])
    out.div_(acc)  # in place: `out` is ours, and a separate result costs a full-size buffer
    return out


def bounded_forward(fn, x: torch.Tensor, scale: int, cap: int, overlap: int, progress=None,
                    on_oom=None):
    """Run :func:`tiled_forward` with the out-of-memory ladder.

    Halves the cap and retries from scratch, stopping at :data:`MIN_CAP`.

    Args:
        fn: Callable mapping ``(n, c, h, w)`` to ``(n, c, h*s, w*s)``.
        x: Input, ``(n, c, h, w)``.
        scale: Output scale.
        cap: Starting tile cap in pixels.
        overlap: Feathered overlap in pixels.
        progress: Optional progress sink.
        on_oom: Optional zero-argument callback run after freeing the allocator and before each
            retry; ``apply_descriptor`` uses it to ask ComfyUI's model manager to make room.
            Exceptions from it are logged and never stop the ladder.

    Returns:
        The blended output.

    Raises:
        torch.cuda.OutOfMemoryError: If the pass still does not fit at the floor.
        MemoryError: If host memory runs out at the floor.
    """
    attempt = int(cap)
    while True:
        try:
            return tiled_forward(fn, x, scale, attempt, overlap, progress)
        except (torch.cuda.OutOfMemoryError, MemoryError) as exc:
            if attempt <= MIN_CAP:
                raise
            attempt = max(MIN_CAP, attempt // 2)
            log.warning(
                "MambaIR: out of memory at a %d px tile, retrying at %d px (%s)",
                attempt * 2, attempt, type(exc).__name__,
            )
            gc.collect()
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
            if on_oom is not None:
                try:
                    on_oom()
                except Exception as callback_exc:  # noqa: BLE001 - never mask the OOM retry
                    log.warning("MambaIR: OOM reload hook failed (%s); retrying anyway",
                                callback_exc)
